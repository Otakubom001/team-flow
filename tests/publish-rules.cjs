const assert=require('node:assert/strict');
const {check,checkUpload,validPostUrl}=require('../publish-rules.js');
const video={name:'ep.mp4',size:1e6,kind:'video',width:1080,height:1920,duration:60};
const result=(duration,platform,extra={})=>check({...video,duration,...extra},platform).kind;
assert.equal(result(90,'facebook'),'preliminary');
assert.equal(result(90.001,'facebook'),'manual');
assert.equal(result(120,'facebook'),'manual');
assert.equal(result(120,'youtube'),'preliminary');
assert.equal(result(120,'tiktok'),'preliminary');
assert.equal(result(180,'youtube'),'preliminary');
assert.equal(result(180.001,'youtube'),'manual');
assert.equal(result(360,'youtube'),'manual');
assert.equal(result(360,'tiktok'),'preliminary');
assert.equal(result(360.001,'tiktok'),'manual');
assert.equal(result(600,'tiktok'),'manual');
assert.equal(result(601,'tiktok'),'manual');
assert.equal(result(Infinity,'youtube'),'unknown');
assert.equal(result(0,'youtube'),'unknown');
assert.equal(result(60,'youtube',{width:1920,height:1080}),'manual');
assert.equal(result(60,'facebook',{size:1e9+1}),'manual');
assert.equal(result(60,'facebook',{name:'ep.webm'}),'manual');
assert.equal(result(60,'facebook',{width:270,height:480}),'manual');
const picture={...video,kind:'image',name:'cover.png',duration:0};
assert.equal(check(picture,'facebook').kind,'preliminary');
assert.equal(check(picture,'youtube').kind,'manual');
assert.equal(check(picture,'tiktok').kind,'manual');
assert.equal(validPostUrl('https://www.youtube.com/watch?v=abc','youtube'),true);
assert.equal(validPostUrl('https://youtu.be/abc','youtube'),true);
assert.equal(validPostUrl('https://youtube.com.evil.example/a','youtube'),false);
assert.equal(validPostUrl('javascript:alert(1)','facebook'),false);
assert.equal(validPostUrl('https://tiktok.com/@test/video/123','youtube'),false);
assert.equal(validPostUrl('','facebook'),true);
const large={...video,size:171700000,duration:139};
for(const platform of ['facebook','tiktok','youtube']){
    assert.equal(checkUpload(large,platform).kind,'manual');
    assert.ok(checkUpload(large,platform).reasons[0].includes('50 MB'));
}
assert.ok(checkUpload(large,'facebook').reasons.some(reason=>reason.includes('90')));
assert.equal(checkUpload({...video,size:52428800},'youtube').kind,'preliminary');
assert.equal(checkUpload({...video,size:52428801},'youtube').kind,'manual');
assert.equal(checkUpload({...picture,size:52428801},'facebook').kind,'manual');
console.log('PASS: duration boundaries, file checks, images, post URLs and website upload cap');
